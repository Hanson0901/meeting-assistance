# 將純文字轉為 segments
# =====================================================
def text_to_segments(text: str, max_chars: int = 400):
    segments = []
    buffer = ""

    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue

        # 如果加上這一行會超過上限 → 先存一段
        if len(buffer) + len(line) + 1 > max_chars:
            segments.append({"text": buffer.strip()})
            buffer = line
        else:
            buffer += " " + line if buffer else line

    # 最後剩下的內容
    if buffer:
        segments.append({"text": buffer.strip()})

    return segments


